#!/usr/bin/env bash
# Builds the Linux release artifacts for one CPU architecture into dist/:
#
#   DupeFinder-<version>-linux-<arch>.AppImage    single-file app, any distro
#   DupeFinder-<version>-linux-<arch>.deb         Debian / Ubuntu / Mint / Pop!_OS
#   DupeFinder-<version>-linux-<arch>.rpm         Fedora / RHEL / Rocky / openSUSE
#   DupeFinder-<version>-linux-<arch>.pkg.tar.zst Arch / Manjaro / EndeavourOS
#   DupeFinder-<version>-linux-<arch>.tar.gz      portable binary + desktop file
#
# Usage: packaging/package-linux.sh [x64|arm64]   (default: the machine's arch)
#
# Needs: cargo-zigbuild (+ zig), cargo-deb, cargo-generate-rpm, bsdtar, zstd, curl.
# The AppImage step downloads appimagetool for the *same* arch, so build each arch on
# a matching machine (CI uses an ARM runner for arm64). The binary is linked against
# glibc 2.28 via zig, so it runs on distros from ~2018 onward.
set -euo pipefail

cd "$(dirname "$0")/.."

ARCH=${1:-}
if [[ -z "$ARCH" ]]; then
    case "$(uname -m)" in
        x86_64) ARCH=x64 ;;
        aarch64 | arm64) ARCH=arm64 ;;
        *) echo "unknown machine arch $(uname -m); pass x64 or arm64" >&2; exit 1 ;;
    esac
fi
case "$ARCH" in
    x64) CPU=x86_64 ;;
    arm64) CPU=aarch64 ;;
    *) echo "unsupported arch: $ARCH (use x64 or arm64)" >&2; exit 1 ;;
esac
TARGET=$CPU-unknown-linux-gnu

VERSION=$(cargo metadata --no-deps --format-version 1 |
    python3 -c 'import json,sys; print(json.load(sys.stdin)["packages"][0]["version"])')
NAME=DupeFinder-$VERSION-linux-$ARCH
BIN=target/$TARGET/release/dupe_finder
DIST=dist
mkdir -p "$DIST"

if [[ "${SKIP_BUILD:-}" != 1 ]]; then
    cargo zigbuild --release --locked --target "$TARGET.2.28"
fi

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT

# Installs the app into a root filesystem layout under $1 (shared by AppImage + Arch).
install_tree() {
    install -Dm755 "$BIN" "$1/usr/bin/dupe_finder"
    install -Dm644 packaging/linux/dupe-finder.desktop "$1/usr/share/applications/dupe-finder.desktop"
    install -Dm644 packaging/linux/dupe-finder.png "$1/usr/share/icons/hicolor/256x256/apps/dupe-finder.png"
    install -Dm644 LICENSE "$1/usr/share/licenses/dupe-finder/LICENSE"
}

# --- tarball ---
mkdir -p "$STAGE/$NAME"
cp "$BIN" packaging/linux/dupe-finder.desktop packaging/linux/dupe-finder.png \
    README.md LICENSE "$STAGE/$NAME/"
tar -C "$STAGE" -czf "$DIST/$NAME.tar.gz" "$NAME"

# --- .deb / .rpm (metadata in Cargo.toml [package.metadata.deb / generate-rpm]) ---
cargo deb --no-build --no-strip --target "$TARGET" --output "$DIST/$NAME.deb"
cargo generate-rpm --target "$TARGET" --output "$DIST/$NAME.rpm"

# --- Arch Linux package (same layout makepkg produces: .PKGINFO + .MTREE + files) ---
PKG=$STAGE/archpkg
install_tree "$PKG"
cat >"$PKG/.PKGINFO" <<EOF
# Generated by packaging/package-linux.sh
pkgname = dupe-finder
pkgbase = dupe-finder
pkgver = $VERSION-1
pkgdesc = Find and remove duplicate files and visually similar photos
url = https://github.com/dhunmoon/PhotoDupeCheckerUI
builddate = $(date +%s)
packager = dhunmoon
size = $(du -sb "$PKG/usr" | cut -f1)
arch = $CPU
license = MIT
depend = glibc
optdepend = libxkbcommon-x11: keyboard input on X11
optdepend = wayland: native Wayland window
optdepend = vulkan-icd-loader: GPU rendering via Vulkan
optdepend = libglvnd: GPU rendering via OpenGL
optdepend = xdg-desktop-portal: native folder picker
EOF
chmod 644 "$PKG/.PKGINFO"
(
    cd "$PKG"
    export LANG=C
    bsdtar --uid 0 --gid 0 --uname root --gname root -czf .MTREE --format=mtree \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO usr
    chmod 644 .PKGINFO .MTREE
    bsdtar --uid 0 --gid 0 --uname root --gname root -cf - .MTREE .PKGINFO usr |
        zstd -q -c -T0 -19 >"$OLDPWD/$DIST/$NAME.pkg.tar.zst"
)

# --- AppImage ---
APPDIR=$STAGE/AppDir
install_tree "$APPDIR"
cp packaging/linux/dupe-finder.desktop packaging/linux/dupe-finder.png "$APPDIR/"
ln -s usr/bin/dupe_finder "$APPDIR/AppRun"
TOOL=${APPIMAGETOOL:-$STAGE/appimagetool}
if [[ ! -x "$TOOL" ]]; then
    curl -sSfL -o "$TOOL" \
        "https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-$CPU.AppImage"
    chmod +x "$TOOL"
fi
# Extract-and-run avoids needing FUSE on the build machine (e.g. CI containers).
APPIMAGE_EXTRACT_AND_RUN=1 ARCH=$CPU "$TOOL" --no-appstream "$APPDIR" "$DIST/$NAME.AppImage"

ls -l "$DIST"
